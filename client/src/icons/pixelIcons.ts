export type IconName = keyof typeof ICONS;

export interface PixelRun {
  x: number;
  y: number;
  width: number;
  color: string;
}

// Merges same-colored pixels in a row into one run, so each icon renders as a few rects.
export function toRuns(rows: readonly string[]): PixelRun[] {
  const runs: PixelRun[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const c = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === c) end++;
      if (c !== '.') runs.push({ x, y, width: end - x, color: ICON_COLORS[c] });
      x = end;
    }
  });
  return runs;
}
